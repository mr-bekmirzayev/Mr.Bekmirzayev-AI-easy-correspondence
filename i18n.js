window.translate = function (lang, key, vars) {
    const dict = window.I18N[lang] || window.I18N.uz;
    let text = dict[key] !== undefined ? dict[key] : (window.I18N.uz[key] !== undefined ? window.I18N.uz[key] : key);
    if (vars) {
        Object.keys(vars).forEach(function (name) {
            text = text.replace(new RegExp("\\{" + name + "\\}", "g"), vars[name]);
        });
    }
    return text;
};
